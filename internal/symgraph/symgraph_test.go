func TestParseRefsAndChunkText(t *testing.T) {
	t.Parallel()

	text := "# Intro\nSee BUG-123 and ./internal/symgraph/parse.go, and ADR-537.\n```md\n# NotAHeading\n```\n## Details\nBody line.\n"
	chunks := ChunkText("docs/guide.md", text)
	if len(chunks) != 2 {
		t.Fatalf("expected 2 markdown chunks, got %d: %+v", len(chunks), chunks)
	}
	if chunks[0].Heading != "Intro" || chunks[1].Heading != "Details" {
		t.Fatalf("unexpected chunk headings: %+v", chunks)
	}

	refs := ParseRefs(text)
	var targets []string
	for _, r := range refs {
		targets = append(targets, r.Target)
	}
	for _, want := range []string{"BUG-123", "ADR-537", "internal/symgraph/parse.go"} {
		if !slices.Contains(targets, want) {
			t.Errorf("ParseRefs missing %q; got %v", want, targets)
		}
	}

	// Must-fail / empty cases
	if got := ChunkText("empty.md", "   \n\t\n"); len(got) != 0 {
		t.Errorf("expected 0 chunks for blank input, got %d", len(got))
	}
	if got := ParseRefs("plain prose with no ids or paths"); len(got) != 0 {
		t.Errorf("expected 0 refs for plain prose, got %+v", got)
	}
}

func TestExtractSymbolsAndRefsGoAndTS(t *testing.T) {
	t.Parallel()

	goSrc := `package demo

import (
	"fmt"
	"example.com/mod/pkg/sub"
)

type Worker interface {
	Run() error
}

type Runner struct{}

func (r *Runner) Run() error {
	fmt.Println("hi")
	return sub.Execute()
}
`
	syms, refs := ExtractSymbolsAndRefs("internal/demo/run.go", goSrc)
	if len(syms) < 3 {
		t.Fatalf("expected >= 3 Go symbols, got %d: %+v", len(syms), syms)
	}
	hasCall := false
	hasImpl := false
	for _, r := range refs {
		if r.Kind == "call" && r.ToPkg == "example.com/mod/pkg/sub" && r.ToName == "Execute" {
			hasCall = true
		}
		if r.Kind == "implements" && r.FromSym == "Worker" && r.ToName == "Runner" {
			hasImpl = true
		}
		if r.ToName == "Println" {
			t.Errorf("stdlib call Println should be filtered out, got %+v", r)
		}
	}
	if !hasCall || !hasImpl {
		t.Errorf("expected cross-pkg call (%v) and implicit implements (%v); refs=%+v", hasCall, hasImpl, refs)
	}

	// Must-fail: excluded vendor path and generated Go file
	if s, r := ExtractSymbolsAndRefs("vendor/pkg/a.go", goSrc); len(s) != 0 || len(r) != 0 {
		t.Errorf("vendor path must be excluded, got %d syms, %d refs", len(s), len(r))
	}
	genSrc := "// Code generated by tool DO NOT EDIT.\n" + goSrc
	if s, r := ExtractSymbolsAndRefs("internal/demo/gen.go", genSrc); len(s) != 0 || len(r) != 0 {
		t.Errorf("generated Go file must be excluded, got %d syms, %d refs", len(s), len(r))
	}

	// TS extraction: exported function + relative import + type ref; local const skipped.
	tsSrc := `import { helperFn, MyType } from './helper';
import * as util from './util';
const hiddenLocal = 42;
export function runTask(x: MyType) {
	util.trace();
	return helperFn(x);
}
`
	tsSyms, tsRefs := ExtractSymbolsAndRefs("web/src/task.ts", tsSrc)
	if len(tsSyms) != 1 || tsSyms[0].Name != "runTask" || tsSyms[0].Exported != 1 {
		t.Fatalf("unexpected TS syms: %+v", tsSyms)
	}
	seenKind := map[string]bool{}
	for _, r := range tsRefs {
		seenKind[r.Kind+":"+r.ToName] = true
	}
	for _, want := range []string{"import:helperFn", "call:helperFn", "call:trace", "type_ref:MyType"} {
		if !seenKind[want] {
			t.Errorf("missing TS ref %q in %+v", want, tsRefs)
		}
	}
}

func TestTarjanAndLouvainAndPackageCycles(t *testing.T) {
	t.Parallel()

	// Cycle a -> b -> c -> a plus isolated d.
	deps := map[string][]string{
		"pkg/a": {"pkg/b"},
		"pkg/b": {"pkg/c"},
		"pkg/c": {"pkg/a"},
		"pkg/d": {"pkg/a"},
	}
	cycles := FindPackageCycles(deps)
	if len(cycles) != 1 || cycles[0] != "pkg/a -> pkg/b -> pkg/c -> pkg/a" {
		t.Fatalf("unexpected cycles: %v", cycles)
	}

	// Must-fail: DAG yields zero cycles.
	dag := map[string][]string{"pkg/a": {"pkg/b"}, "pkg/b": {"pkg/c"}}
	if got := FindPackageCycles(dag); len(got) != 0 {
		t.Errorf("DAG must yield 0 cycles, got %v", got)
	}
	if got := TarjanSCC(1, nil); len(got) != 0 {
		t.Errorf("single-node TarjanSCC must be empty, got %v", got)
	}

	// Louvain: two disconnected triangles form 2 deterministic communities.
	edges := []LouvainEdge{
		{U: 0, V: 1, Weight: 5}, {U: 1, V: 2, Weight: 5}, {U: 0, V: 2, Weight: 5},
		{U: 3, V: 4, Weight: 5}, {U: 4, V: 5, Weight: 5}, {U: 3, V: 5, Weight: 5},
	}
	comms := LouvainCommunities(6, edges)
	if len(comms) != 6 {
		t.Fatalf("expected 6 community assignments, got %d", len(comms))
	}
	if comms[0] != comms[1] || comms[1] != comms[2] || comms[3] != comms[4] || comms[4] != comms[5] || comms[0] == comms[3] {
		t.Errorf("expected two distinct communities for two triangles, got %v", comms)
	}
	if got := LouvainCommunities(0, nil); got != nil {
		t.Errorf("numNodes=0 must return nil, got %v", got)
	}
}

func TestVendoredSkillPathsAndResolveImports(t *testing.T) {
	t.Parallel()

	for _, p := range []string{"skills/foo/references/doc.md", ".agents/skills/bar/assets/tpl.go"} {
		if !IsVendoredSkillPath(p) {
			t.Errorf("expected IsVendoredSkillPath(%q)=true", p)
		}
	}
	for _, p := range []string{"skills/foo/SKILL.md", "skills/foo/scripts/run.sh", "internal/search/parse.go", ""} {
		if IsVendoredSkillPath(p) {
			t.Errorf("expected IsVendoredSkillPath(%q)=false", p)
		}
	}

	goMods := map[string]string{"example.com/app": "."}
	pkgSet := map[string]bool{"internal/a": true, "web/ui": true}
	fileByStem := map[string]string{"web/ui/btn": "web/ui/btn.tsx"}

	if pkg, _, ok := ResolveImportTarget("cmd/main.go", "example.com/app/internal/a", goMods, pkgSet, fileByStem); !ok || pkg != "internal/a" {
		t.Errorf("Go import resolve failed: pkg=%q ok=%v", pkg, ok)
	}
	if _, _, ok := ResolveImportTarget("cmd/main.go", "other.org/mod/x", goMods, pkgSet, fileByStem); ok {
		t.Errorf("unknown Go module must not resolve")
	}
	if pkg, f, ok := ResolveImportTarget("web/app.ts", "./web/ui/btn", goMods, pkgSet, fileByStem); !ok || pkg != "web/ui" || f != "web/ui/btn.tsx" {
		t.Errorf("TS import resolve failed: pkg=%q file=%q ok=%v", pkg, f, ok)
	}
	if _, _, ok := ResolveImportTarget("web/app.ts", "../escape/secret", goMods, pkgSet, fileByStem); ok {
		t.Errorf("escaping TS import must not resolve")
	}
}

func TestExtractCompactCapsuleMeta(t *testing.T) {
	t.Parallel()

	capsule := strings.Join([]string{
		"[Hop 0] internal/a/foo.go:10-20 (Foo)",
		"[Hop 1] internal/b/bar.go:5-9 (Bar) snippet — func Bar() [EXTRACTED]",
		"malformed line without brackets",
	}, "\n")
	pivots, files, count := ExtractCompactCapsuleMeta(capsule)
	if count != 2 {
		t.Fatalf("expected symCount=2, got %d", count)
	}
	if !slices.Equal(files, []string{"internal/a/foo.go"}) {
		t.Errorf("expected hop0 files [internal/a/foo.go], got %v", files)
	}
	if len(pivots) == 0 {
		t.Errorf("expected parsed pivots, got empty")
	}

	// Must-fail / empty capsule
	p2, f2, c2 := ExtractCompactCapsuleMeta("no hop markers here\n[Hop 0] nospace\n")
	if len(p2) != 0 || len(f2) != 0 || c2 != 1 {
		t.Errorf("unexpected malformed capsule meta: pivots=%v files=%v count=%d", p2, f2, c2)
	}
}

func TestGraphRankReverseBlastAndBoundedHelpers(t *testing.T) {
	t.Parallel()

	files := []FileMeta{
		{Path: "internal/a/a.go", OID: "o1", Pkg: "internal/a", LineCount: 40},
		{Path: "internal/b/b.go", OID: "o2", Pkg: "internal/b", LineCount: 30},
		{Path: "internal/b/b_test.go", OID: "o3", Pkg: "internal/b", LineCount: 20},
	}
	syms := []RankedSymbol{
		{Idx: 0, Path: "internal/a/a.go", OID: "o1", Name: "CoreFn", Kind: "func", Pkg: "internal/a", StartLine: 1, EndLine: 10, Sig: "func CoreFn()", Exported: true},
		{Idx: 1, Path: "internal/b/b.go", OID: "o2", Name: "CallerFn", Kind: "func", Pkg: "internal/b", StartLine: 1, EndLine: 10, Sig: "func CallerFn()", Exported: true},
		{Idx: 2, Path: "internal/b/b_test.go", OID: "o3", Name: "TestCaller", Kind: "func", Pkg: "internal/b", StartLine: 1, EndLine: 10, Sig: "func TestCaller(t *testing.T)", Exported: true},
	}
	g := NewGraphWithMeta(syms, files, map[string]string{"example.com/m": "."})
	g.AddImportRef(RawSymRef{Path: "internal/b/b.go", OID: "o2", FromSym: "<import>", ToPkg: "example.com/m/internal/a", ToName: "<import>", Kind: "import", Confidence: ConfidenceExtracted, Weight: WeightExtracted, Line: 3})
	g.AddRawRef(RawSymRef{Path: "internal/b/b.go", OID: "o2", FromSym: "CallerFn", ToPkg: "example.com/m/internal/a", ToName: "CoreFn", Kind: "call", Confidence: ConfidenceExtracted, Weight: WeightExtracted, Line: 5})
	g.AddRawRef(RawSymRef{Path: "internal/b/b_test.go", OID: "o3", FromSym: "TestCaller", ToPkg: "", ToName: "CallerFn", Kind: "call", Confidence: ConfidenceExtracted, Weight: WeightExtracted, Line: 5})

	ranked := g.Rank("CoreFn", nil)
	if len(ranked) != 3 || ranked[0].Name != "CoreFn" {
		t.Fatalf("expected CoreFn ranked first, got %+v", ranked)
	}
	direct, trans, tests := g.collectReverseBlast([]int{0}, map[string]bool{})
	if len(direct) != 1 || len(trans) != 0 || len(tests) != 1 {
		t.Errorf("unexpected reverse blast: direct=%v trans=%v tests=%v", direct, trans, tests)
	}
	callers, callees, compactTests := g.collectCompactEdges([]int{1})
	if len(callers) != 1 || len(callees) != 1 || len(compactTests) != 1 {
		t.Errorf("unexpected compact edges: callers=%v callees=%v tests=%v", callers, callees, compactTests)
	}
	pkgs, weights := g.collectPackageEdgeWeights(false)
	if !slices.Equal(pkgs, []string{"internal/a", "internal/b"}) || weights[[2]string{"internal/b", "internal/a"}] == 0 {
		t.Errorf("unexpected pkg edge weights: pkgs=%v weights=%v", pkgs, weights)
	}

	// Bounded like terms & priority partition
	exact, long, dots, hasDot := collectBoundedLikeTermsWithMin([]string{"the", "pkg/a.go", "Store.LoadWidget", "x"}, 4)
	if !hasDot || !slices.Contains(dots, "loadwidget") || !slices.Contains(long, "store.loadwidget") || len(exact) == 0 {
		t.Errorf("unexpected bounded like terms: exact=%v long=%v dots=%v hasDot=%v", exact, long, dots, hasDot)
	}
	prio, other := partitionPrioritySymNames(syms, []string{"CoreFn"}, 2)
	if !slices.Equal(prio, []string{"CoreFn"}) || len(other) != 1 {
		t.Errorf("unexpected priority partition: prio=%v other=%v", prio, other)
	}
}

package harness

import (
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
)

// Marker is the first line of the context fyr generates, naming where
// to edit it and how to redeploy.
const Marker = "<!-- generated by fyr from the fyr harness repo: edit context/*.md, agents/ or skills/ there and run `fyr install` -->"

// Canary is the last line of every rendered context. A smoke check asks the
// CLI for the word; only a file loaded to its end can answer, which is how the
// Antigravity block cap (BUG-085, REQUIREMENTS § Known limits) is caught.
const Canary = "Canary: this context ends with the word GANNET."

// RenderContext assembles the deployed context: context/AGENTS.md first,
// every other context/*.md in name order, then the compact inventory, then
// the Canary line, which is last so a check that reads it proves the whole
// file loaded.
func RenderContext(src Source, inv Inventory) ([]byte, error) {
	if err := checkManagedTree(src); err != nil {
		return nil, err
	}
	main, err := fs.ReadFile(src.FS, "context/AGENTS.md")
	if err != nil {
		return nil, fmt.Errorf("reading context: %w", err)
	}
	extras, err := fs.Glob(src.FS, "context/*.md")
	if err != nil {
		return nil, err
	}
	sort.Strings(extras)

	var b strings.Builder
	b.WriteString(Marker + "\n")
	b.Write(main)
	for _, p := range extras {
		if path.Base(p) == "AGENTS.md" {
			continue
		}
		data, err := fs.ReadFile(src.FS, p)
		if err != nil {
			return nil, err
		}
		b.WriteString("\n")
		b.Write(data)
	}
	b.WriteString("\n")
	b.WriteString(RenderInventoryCompact(inv))
	b.WriteString("\n" + Canary + "\n")
	return []byte(b.String()), nil
}
